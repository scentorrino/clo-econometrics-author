# ---- The mandatory empirical-vs-asymptotic quantile comparison -------------
qblock <- function(o) {
  z <- (o$q_emp - o$q_asy) / o$q_se
  c(sprintf("%s & %s & %.3f & %s (%s) & %s & %s \\\\",
            c(sprintf("%d", o$L_cells), rep("", length(Q_PROBS) - 1L)),
            c(big(o$n), rep("", length(Q_PROBS) - 1L)),
            Q_PROBS, fmt(o$q_emp, 3), fmt(o$q_se, 3), fmt(o$q_asy, 3),
            fmt(z, 2)),
    "\\addlinespace")
}

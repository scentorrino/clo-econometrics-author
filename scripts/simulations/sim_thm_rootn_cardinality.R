# ---- Design validity at each cardinality -----------------------------------
#
# The balancing residual is reported BOTH raw and in the units that decide
# whether it matters. A2's failure enters the bias expansion bilinearly in
# (nu_{g_star}, h), so by Cauchy-Schwarz under D7 its worst-case contribution to
# sqrt(n)(theta-hat - theta) is sqrt(n) ||nu_{g_star}|| c_delta delta_n. That is
# the number to compare against the leading remainder sqrt(n) (c_delta delta_n)^2
# the design is actually testing -- not the raw residual, which is scale-free
# and says nothing on its own.
vtab <- rbindlist(lapply(names(VAL), function(k) {
  v <- VAL[[k]]; e <- ES[[k]]
  nmax <- max(N_GRID)
  data.table(
    L = v$L_cells, ncol = v$n_ell_col,
    bal = v$balancing_rel_resid,
    a2_price = sqrt(nmax) * max(e$l2_resid) * C_DELTA * rate_delta_n(nmax),
    lead = sqrt(nmax) * (C_DELTA * rate_delta_n(nmax))^2,
    psi_t = max(abs(v$mean_psi / v$mean_psi_se)),
    dzdu = max(abs(v$E_dz_du)), kj = v$kappa_J,
    pmin = v$min_cell_prob, eps = v$eps_varrho,
    lam = v$lambda_min_Omega, lam_thy = v$eps_Omega_thy,
    ellsup = v$ell_sup, sdinf = sqrt(as.numeric(
      t(THETA_MIX) %*% POP[[k]]$V %*% THETA_MIX)))
}))
setorder(vtab, L)
# TRANSPOSED: the diagnostics are the rows and the cardinalities are the
# columns, because the question this table answers is "what moved when sans-L
# moved" and a two-column contrast is what makes that readable. Every threshold
# a reader needs is a ROW of the table, not a note pasted into its body
# (INV-1 / table standards): the realised quantity and the bound it must clear
# sit adjacent, so the comparison is in the body and not in the caption.
esc <- function(x, d) fmt(x, d)
sci <- function(x) formatC(x, format = "e", digits = 1)
drow <- function(lab, vals) sprintf("%s & %s \\\\", lab, paste(vals, collapse = " & "))
writeLines(c(
  sprintf("\\begin{tabular}{l%s}", strrep("r", nrow(vtab))), "\\toprule",
  drow("", sprintf("$\\mathsf L = %d$", vtab$L)),
  "\\midrule",
  sprintf("\\multicolumn{%d}{l}{\\textit{The design at this cardinality}} \\\\",
          nrow(vtab) + 1L),
  drow("\\quad Non-base contrasts, $\\mathsf L-1$", vtab$L - 1L),
  drow("\\quad Columns in the population balancing solve", vtab$ncol),
  drow("\\quad Realised cell shares", vapply(as.character(vtab$L), function(k)
    paste(fmt(VAL[[k]]$cell_shares, 3), collapse = "/"), character(1))),
  "\\addlinespace",
  sprintf("\\multicolumn{%d}{l}{\\textit{A2: the balancing equation, and what its failure costs}} \\\\",
          nrow(vtab) + 1L),
  drow("\\quad Relative residual $\\|\\nu_{g_\\star}\\|/\\|\\nu_{\\Delta Z}\\|$", sci(vtab$bal)),
  drow("\\quad Priced, $\\sqrt n\\,\\|\\nu_{g_\\star}\\|\\,c_\\delta\\delta_n$", sci(vtab$a2_price)),
  drow("\\quad Against the leading remainder $\\sqrt n\\,c_\\delta^2\\delta_n^2$", esc(vtab$lead, 2)),
  "\\addlinespace",
  sprintf("\\multicolumn{%d}{l}{\\textit{A4(i): overlap, realised against the bound it must clear}} \\\\",
          nrow(vtab) + 1L),
  drow("\\quad $\\min_l\\varrho_l$ (all cells, base included)", esc(vtab$pmin, 4)),
  drow("\\quad Floor $\\varepsilon_\\varrho$", esc(vtab$eps, 2)),
  drow("\\quad $\\lambda_{\\min}(\\Omega)$", esc(vtab$lam, 4)),
  drow("\\quad Floor $\\varepsilon_\\varrho/\\mathsf L$", esc(vtab$lam_thy, 4)),
  "\\addlinespace",
  sprintf("\\multicolumn{%d}{l}{\\textit{What the estimator inherits}} \\\\",
          nrow(vtab) + 1L),
  drow("\\quad $\\kappa(J)$", esc(vtab$kj, 2)),
  drow("\\quad $\\sup|\\ell_\\star|$, the (R-a) budget", esc(vtab$ellsup, 2)),
  drow("\\quad $\\mathrm{sd}_\\infty$ of the mixed direction", esc(vtab$sdinf, 3)),
  drow("\\quad $\\max_m|t|$ on $E[\\psi_\\star]$", esc(vtab$psi_t, 2)),

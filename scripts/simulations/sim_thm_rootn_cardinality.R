# ============================================================================
# sim_thm_rootn_cardinality.R   --   scope S1
#
# DOES thm:rootn's LIMIT LAW HOLD AT sans-L = 4 ON THE PAPER'S OWN DESIGN?
#
# The limit law of thm:rootn is
#   sqrt(n)(theta-hat - theta_dagger)
#      = J^{-1} n^{-1/2} sum_i psi_star(O_i) + o_P(1)  ->  N(0, J^{-1} Sigma J^{-1'})
# with J and Sigma of eq:JSig. The theorem is stated at a general finite
# instrument, W in {0, ..., sans-L - 1}; Section 5's evidence for it was BINARY
# on both of its designs (sim_thm_rootn_dgp.R and sim_thm_rootn_headroom_dgp.R
# were each `pw <- cbind(1 - rr, rr)`). This arm supplies the cardinality column
# that scope was missing, ON ONE DESIGN, WITH ONE FACTOR VARYING.
#
# ---------------------------------------------------------------------------
# WHAT VARIES, AND WHAT EXPLICITLY DOES NOT
#
# VARIES: sans-L in {2, 4}, and the two primitives a cardinality forces -- the
# number of propensity index functions and the number of first-stage shifts --
# both generated by the rule of design decision D8, which RETURNS THE SHIPPED
# BINARY DESIGN at sans-L = 2.
#
# HELD FIXED, and this is the list a reader is entitled to check:
#   design           DGP-A, the favourable one, primitive for primitive
#   configuration    (mu, s, a, alpha) = (2, 3, 3/4, 0.32), rem:h6bandwidth(5)
#   c_delta          0.25 at every cell
#   c_eps, c_r       1 at every cell
#   h geometry       "smooth", h_bias = 0
#   n grid           1,000 / 8,000 / 64,000 -- the SAME three points at both
#   B                5,000 at every cell, so no cell's verdict rests on its own
#                    noise floor
#   overlap floor    eps_varrho = 0.10 at both cardinalities. A4(i) permits it
#                    up to sans-L = 9, so holding it fixed is feasible, not
#                    lucky; what moves is the INDUCED floor eps_varrho/sans-L of
#                    eq:omegafloor, which is a consequence and not a second dial
#   ridge            1e-10, absolute, in the population balancing solve -- NOT
#                    rescaled with the cardinality, and the achieved residual is
#                    reported at both
#   nuisance regime  INJECTED at controlled rates at both cardinalities. This is
#                    the arm's whole point (D3e): a comparison in which one
#                    column estimates its nuisances and the other injects them
#                    is a two-factor contrast, and tab:app-theta shipped exactly
#                    that defect once already
#
# The cardinality columns are NOT paired on a shared draw: each cell runs its
# own replications. Nothing here is a paired difference -- every statistic is
# compared to ITS OWN asymptotic target (N(0,1) for the studentised statistic,
# nominal for coverage), which is the comparison thm:rootn makes and the one
# that needs no pairing.
#
# ---------------------------------------------------------------------------
# WHAT THIS ARM DOES NOT COVER, SAID PLAINLY
#
#   * THE PHI-STEP IS BINARY AND STAYS BINARY. sim_thm_rootn_phistep.R's
#     `ww <- wt * Wt_mat[, tt]` becomes a double integral over (t, cell) under
#     B1(iv.d)'s Pi_w at sans-L >= 3, which changes the estimator being
#     simulated and not merely the loop. It is out of scope here by decision,
#     not by oversight.
#   * DGP-B is not run at sans-L = 4. The stress design is a separate question
#     from the cardinality one and mixing them would put two factors in one row.
#   * sans-L = 3 is not run. The contrast is 2-against-4; the intermediate point
#     buys a shape, not a verdict.
#   * This arm says nothing about whether any particular nuisance ESTIMATOR
#     attains the injected rates at sans-L >= 3. That is what the shipped-engine
#     arms (sim_multinomial_*.R) measure, on a different design.
#
# ---------------------------------------------------------------------------
# PROVENANCE OF one_rep_card()
#
# It is the sans-L-aware counterpart of one_rep_full() in
# sim_thm_rootn_limitlaw.R. The two differ ONLY at the three points where the
# contrast index is summed out -- psi, J-hat and the nuisance-size diagnostics --
# and they are required to agree BIT FOR BIT at sans-L = 2, which
# sim_thm_rootn_l2identity.R checks against the pre-cardinality baseline and
# which the design-validity block below re-checks in place.
#
# Outputs
#   paper/tables/sim/sim_thm_rootn_cardinality.tex            (bare tabular, INV-13)
#   paper/tables/sim/sim_thm_rootn_cardinality_seunits.tex    (bare tabular)
#   paper/tables/sim/sim_thm_rootn_cardinality_quantiles.tex  (bare tabular)
#   paper/tables/sim/sim_thm_rootn_cardinality_design.tex     (bare tabular)
#   paper/figures/sim/sim_thm_rootn_cardinality_qq.pdf        (no in-figure title, INV-12)
#   quality_reports/sim/sim_thm_rootn_cardinality.rds
# ============================================================================

